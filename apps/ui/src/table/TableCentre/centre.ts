/**
 * Ложится ли карта на это место ровно или под своим углом.
 *
 * `square` — ровно. `own` — под своим, и КАКИМ именно, здесь не сказано: это
 * дело сцены и такта. Ни величины, ни знака, ни одинаковости между картами
 * `own` не утверждает — у кучи сброса, например, угол свой у каждой карты, из
 * `scatterAt`, и он должен таким и остаться.
 *
 * Характер, а не значение: он отвечает на вопрос «кто положил карту» (I11,
 * `docs/animations/README.md`), а не на вопрос «на сколько градусов».
 */
export type CentreTilt = 'square' | 'own'

/**
 * Наборы мест по игровым ситуациям. Ситуация — это то, что видит игрок за
 * столом, а не то, как оно устроено внутри: «релиз платит за себя» — набор из
 * двух мест, «атаку накрыли защитой» — из трёх.
 *
 * Набор существует, только если сцена его показала. Новая ситуация добавляет
 * свой набор сюда — и до тех пор её мест нет, а не «наверное такие же».
 */
// Характер наклона принадлежит НАБОРУ, а не месту: одно и то же место читается
// по-разному в зависимости от того, кто карту туда положил. Вскрытый системой
// триггер лежит в центре ровно, прилетевшая из руки атака — на том же месте под
// своим углом. Это инвариант I11 (`docs/animations/README.md`).
export const CENTRE_SETS = {
  /** карта, которую в центр выложила система: добор, вскрытый триггер, 503 */
  reveal: { centre: 'square' },
  // Обе карты ровные, хотя обе пришли из руки, и это не исключение из I11, а его
  // точная формулировка: наклон отмечает СЫГРАННУЮ карту, брошенную в момент.
  // Релиз, стоящий в ожидании оплаты, ещё не сыгран — он ждёт; и ровным он
  // останется в своей зоне, потому что релиз в зоне это состояние стола, а не
  // ход. Под углом там лежит подоткнутый Code Review (`PAIR_AUX`), а не сам
  // релиз.
  /** релиз стоит в центре и открыто платит свою цену */
  release: { stage: 'square', cost: 'square' },
  /** атака прилетела, её накрыли защитой, рядом ждёт судо */
  defence: { sudo: 'own', centre: 'own', cover: 'own' },
  /** карта AI: слева триггер, из-за которого она пришла, справа сам эффект */
  ai: { cause: 'square', effect: 'square' },
  /** эффект AI требует карту: отданная встаёт открыто справа от него */
  aiPick: { cause: 'square', effect: 'square', picked: 'square' },
} satisfies Record<string, Partial<Record<CentreSlot, CentreTilt>>>

export type CentreSet = keyof typeof CENTRE_SETS

/**
 * CSS-трансформ места: сдвиг от центра стола. Пара к `CENTRE_TOP` — вместе они
 * дают полное позиционирование места внутри стола.
 */
export const centreTransform = (slot: CentreSlot): string => {
  const { dx } = CENTRE_SLOTS[slot]
  return dx === 0 ? 'translate(-50%, -50%)' : `translate(calc(-50% + ${dx}px), -50%)`
}
