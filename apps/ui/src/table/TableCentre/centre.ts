// ЕДИНЫЙ ИСТОЧНИК ГЕОМЕТРИИ ЦЕНТРА СТОЛА.
//
// Центр — это не блок с содержимым, а набор ИМЕНОВАННЫХ МЕСТ: куда встаёт
// разыгранный релиз, где лежит его цена, куда прилетает атака и что накрывает
// её сверху. Пустой центр выглядит как ничто, поэтому его так легко описать
// дважды — сцена рисует свои `position: absolute` в CSS, борд рисует такие же
// рядом, и совпадают они только вручную.
//
// Отсюда правило: места живут ЗДЕСЬ, в TS, а не в CSS-модуле. Разница не
// стилистическая — из CSS-модуля значение нельзя ни переиспользовать, ни
// проверить тестом (jsdom стили не грузит), а отсюда можно и то и другое.
// Ровно так же устроен веер руки: `table/Hand/fan.ts` — единственный источник
// его геометрии, и раскладка с приземлением считаются по одной формуле оттуда.

/** Имя места в центре. Не «слот номер два», а то, чем оно является в игре. */
export type CentreSlot = 'sudo' | 'stage' | 'centre' | 'cover' | 'cost'

export interface CentreSlotGeom {
  /** сдвиг от центра стола по горизонтали, px (0 — ровно по центру) */
  dx: number
  /** порядок перекрытия: накрывающая карта обязана лежать выше накрытой */
  z: number
}

/**
 * Ширина карты в центре. Одна на все места: центр — это стол, а не веер, и
 * карта, положенная на стол, не меняет размер от того, какое место заняла.
 */
export const CENTRE_CARD_W = 150

/**
 * Высота, на которой стоит ряд, в процентах от высоты стола. Не 50%: центр
 * поднят над серединой, потому что снизу стол занимает рука.
 */
export const CENTRE_TOP = 42

/**
 * Места центра. Значения перенесены дословно из одобренной сцены
 * `DefenseReleaseStory` — она остаётся визуальным источником, здесь только
 * единственное место, где эти числа записаны.
 */
export const CENTRE_SLOTS: Record<CentreSlot, CentreSlotGeom> = {
  // судо ждёт своей защиты слева от атаки — оно ещё не часть пары
  sudo: { dx: -180, z: 9 },
  // разыгранный релиз стоит и ждёт, пока за него заплатят
  stage: { dx: -92, z: 10 },
  // то, что происходит сейчас: прилетевшая атака, вскрытый триггер, карта AI
  centre: { dx: 0, z: 10 },
  // защита накрывает атаку — со смещением и своим наклоном, чтобы читались две
  // игры, а не одна аккуратная стопка; поверх накрытой ОБЯЗАТЕЛЬНО
  cover: { dx: 0, z: 11 },
  // цена релиза, открыто рядом с ним
  cost: { dx: 92, z: 10 },
}

/**
 * Наборы мест по игровым ситуациям. Ситуация — это то, что видит игрок за
 * столом, а не то, как оно устроено внутри: «релиз платит за себя» — набор из
 * двух мест, «атаку накрыли защитой» — из трёх.
 *
 * Набор существует, только если сцена его показала. Новая ситуация (503,
 * выбывание, карты AI) добавляет свой набор сюда — и до тех пор её мест нет,
 * а не «наверное такие же».
 */
export const CENTRE_SETS = {
  /** карта, которую в центр выложила система: добор, вскрытый триггер, AI */
  reveal: ['centre'],
  /** релиз стоит в центре и открыто платит свою цену */
  release: ['stage', 'cost'],
  /** атака прилетела, её накрыли защитой, рядом ждёт судо */
  defence: ['sudo', 'centre', 'cover'],
} satisfies Record<string, CentreSlot[]>

export type CentreSet = keyof typeof CENTRE_SETS

/**
 * CSS-трансформ места: сдвиг от центра стола. Пара к `CENTRE_TOP` — вместе они
 * дают полное позиционирование места внутри стола.
 */
export const centreTransform = (slot: CentreSlot): string => {
  const { dx } = CENTRE_SLOTS[slot]
  return dx === 0 ? 'translate(-50%, -50%)' : `translate(calc(-50% + ${dx}px), -50%)`
}
