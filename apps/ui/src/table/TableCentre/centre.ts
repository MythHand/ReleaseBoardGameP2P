  sudo: { dx: -180, w: 150, z: 9, from: 'DefenseReleaseStory' },
  // разыгранный релиз стоит и ждёт, пока за него заплатят
  stage: { dx: -92, w: 150, z: 10, from: 'DefenseReleaseStory' },
  // триггер, из-за которого всё случилось: карта AI, вскрытая при доборе
  cause: { dx: -107, w: 150, z: 0, from: 'DrawCardStory · AiCardsStory' },
  // то, что происходит сейчас: прилетевшая атака, вскрытый триггер, 503
  centre: { dx: 0, w: 150, z: 10, from: 'CardPlayStory · Error503Story · DefenseReleaseStory' },
  // защита, накрывающая атаку: то же место, слой выше
