// ЕДИНЫЙ ИСТОЧНИК ГЕОМЕТРИИ ЦЕНТРА СТОЛА.
//
// Центр — это не блок с содержимым, а набор ИМЕНОВАННЫХ МЕСТ: куда встаёт
// разыгранный релиз, где лежит его цена, куда прилетает атака, что накрывает её
// сверху, где стоит вскрытый триггер и его эффект. Пустое место выглядит как
// ничто, поэтому его так легко описать дважды — сцена рисует свои координаты в
// CSS, борд рисует такие же рядом, и совпадают они только вручную.
//
// Отсюда правило: места живут ЗДЕСЬ, в TS, а не в CSS-модуле. Разница не
// стилистическая — из CSS-модуля значение нельзя ни переиспользовать, ни
// проверить тестом (jsdom стили не грузит), а отсюда можно и то и другое.
// Ровно так же устроен веер руки: `table/Hand/fan.ts` — единственный источник
// его геометрии, и раскладка с приземлением считаются по одной формуле оттуда.
//
// Все значения перенесены дословно из одобренных сцен плейграунда; у каждого
// места записано, откуда оно взято. Сцены остаются визуальным источником, здесь
// только единственное место, где эти числа записаны.
//
// ГРАНИЦА, И ОНА ЖЁСТКАЯ: место — это КУДА карта прилетает. Угла здесь нет.
//
// Наклоны в проекте детерминированно случайные: `scatterAt`
// (`@/animations/scatter`) считает угол хешем от ключа, поэтому у каждой карты
// он свой, у всех пиров одинаковый, и полёт с покоем читают ОДИН разброс — карта
// приземляется ровно туда, где потом лежит. Стоит месту начать диктовать позу, и
// это рушится дважды: разнообразие схлопывается в один угол на всех, а карта,
// которой полёт уже посчитал разброс, садится в чужой — то есть возвращается
// подскок на последнем кадре, ради устранения которого разброс и был сделан
// единым источником.
//
// Поэтому у места — `dx` / `w` / `z` и ничего больше. У НАБОРА записано, ложится
// ли карта на это место ровно или под своим углом, но именно ХАРАКТЕРОМ, а не
// числом. Значения по умолчанию тоже нет и быть не должно: дефолт — это то, что
// копируют, и через две сцены он станет общим наклоном.

import type { CSSProperties } from 'react'

/** Имя места в центре. Не «слот номер два», а то, чем оно является в игре. */
export type CentreSlot =
  | 'sudo'
  | 'stage'
  | 'cause'
  | 'centre'
  | 'cover'
  | 'cost'
  | 'effect'
  | 'picked'

export interface CentreSlotGeom {
  /** сдвиг от центра стола по горизонтали, px (0 — ровно по центру) */
  dx: number
  /** ширина карты на этом месте, px — она НЕ одна на все места */
  w: number
  /** сцена плейграунда, из которой перенесено значение */
  from: string
}

/**
 * Как место ведёт себя в конкретной ситуации: ложится ли карта ровно и на каком
 * слое стоит место.
 *
 * Слой — тоже свойство НАБОРА, а не места, и по той же причине, что и наклон:
 * он существует только там, где места перекрываются. В защите их три друг на
 * друге, поэтому 9/10/11; в вскрытии место одно и слоя нет вовсе; у карты AI он
 * есть только у эффекта. Проставить слой месту «на всякий случай» значит
 * создать контекст наложения там, где сцена его не создавала.
 *
 * `z` отсутствует — слоя нет, элемент участвует в общем порядке документа.
 */
export interface CentrePlace {
  tilt: CentreTilt
  z?: number
}

/**
 * Высота, на которой стоит ряд, в процентах от высоты стола. Одна на все места
 * и на все сцены. Не 50%: центр поднят над серединой, потому что снизу стол
 * занимает рука.
 */
export const CENTRE_TOP = 42

/** Ширина карты, которую центр использует чаще всего — та же, что у веера. */
export const CENTRE_CARD_W = 150

